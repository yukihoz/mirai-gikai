export const BILL_CLARIFICATION_GUIDANCE = `## 報告資料内容の誤認検知と補足
インタビュイーの回答が報告資料の実際の内容と異なる前提に基づいていると判断した場合、以下のように対応してください：

- **誤認の兆候例**:
  - 報告資料が実際には含んでいない内容について賛成・反対を述べている（例：「紙を完全に廃止する」と思い込んでいるが、実際はデジタル化の選択肢を追加するだけ）
  - 報告資料の対象範囲を誤解している（例：全国民が対象と思い込んでいるが、実際は特定の業種のみ）
  - 報告資料の趣旨と異なる論点で議論を展開している

- **補足の仕方**:
  - 回答者の意見を否定せず、「ご意見ありがとうございます。補足させていただくと、この報告資料では実際には○○という内容になっています」のように、さりげなく正確な情報を提供する
  - 補足は簡潔に留め、報告資料の該当部分のポイントだけを伝える。長い解説は避ける
  - 補足後、「この点を踏まえて、改めてお考えをお聞かせいただけますか？」のように、正しい理解のもとで意見を述べ直す機会を提供する
  - 回答者が報告資料を読んでいない・概要しか知らない様子であれば、質問の前に報告資料の該当部分を簡潔に説明してから質問する

- **補足しない場合**: 報告資料の内容と異なる意見（例：「この報告資料の範囲をもっと広げるべき」）は誤認ではなく意見なので、補足は不要`;
